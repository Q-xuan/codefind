"""Read-only context-strategy experiment; not the production XLSX reader.

Usage: python tools/eval_xlsx_context.py [--self-test]
Synthetic cases use only Python stdlib.
No workbook is saved and no formulas are evaluated.
"""
import argparse
import json
import time
from dataclasses import dataclass, field


@dataclass
class Sheet:
    cells: dict
    comments: dict = field(default_factory=dict)
    merges: list = field(default_factory=list)


@dataclass
class Case:
    name: str
    sheet: Sheet
    anchor: tuple
    gold: set
    aliases: tuple = ("参数1", "param1")
    cohort: str = "synthetic"


def select(case, strategy, cap=96):
    """Return original cell evidence only; never infer business semantics."""
    if strategy == "adaptive":
        structured = select(case, "structure", cap)
        if structured["field_candidates"]:
            return {**structured, "selected_strategy": "structure"}
        fallback = select(case, "row_headers", cap)
        return {**fallback, "selected_strategy": "row_headers", "inspected_positions": structured["inspected_positions"] + fallback["inspected_positions"]}
    s, (row, col) = case.sheet, case.anchor
    fields = 0
    inspected, chosen = set(), []

    def read(r, c):
        inspected.add((r, c))
        return s.cells.get((r, c))

    def add(r, c):
        read(r, c)
        for kind, data in (("value", s.cells), ("comment", s.comments)):
            key = (r, c, kind)
            if (r, c) in data and key not in chosen:
                chosen.append(key)
        for r1, c1, r2, c2 in s.merges:
            if r1 <= r <= r2 and c1 <= c <= c2 and (r1, c1) != (r, c):
                key = (r1, c1, "value")
                if (r1, c1) in s.cells and key not in chosen:
                    read(r1, c1)
                    chosen.append(key)

    if strategy == "window":
        for r in range(max(1, row - 2), row + 3):
            for c in range(max(1, col - 4), col + 5):
                add(r, c)
    elif strategy == "row_headers":
        for c in range(1, 65):
            add(row, c)
        for r in range(1, min(row, 13)):
            for c in range(1, 65):
                add(r, c)
    elif strategy == "structure":
        # Bounded row-key matching locates candidate blocks, not proven joins.
        value = read(row, col)
        keys = [c for c in range(1, 65) if read(row, c) == value and value is not None]
        add(row, col)
        for i, keycol in enumerate(keys):
            add(row, keycol)
            end = keys[i + 1] if i + 1 < len(keys) else 65
            for c in range(keycol + 1, end):
                headers = []
                for r in range(row - 1, max(0, row - 33), -1):
                    raw = read(r, c)
                    # Keep all matching header cells, not an assumed unique mapping.
                    if isinstance(raw, str) and raw.strip().lower() in case.aliases:
                        headers.append(r)
                if headers:
                    fields += 1
                    for r in headers:
                        add(r, c)
                    add(row, c)
    else:
        raise ValueError(strategy)
    truncated = len(chosen) > cap
    chosen = chosen[:cap]
    chars = sum(len(str((s.cells if kind == "value" else s.comments)[(r, c)])) for r, c, kind in chosen)
    found = set(chosen) & case.gold
    return {
        "covered": len(found), "required": len(case.gold),
        "complete": len(found) == len(case.gold),
        "returned": len(chosen), "non_gold": len(chosen) - len(found),
        "characters": chars, "inspected_positions": len(inspected),
        "truncated": truncated,
        "field_candidates": fields,
    }


def synthetic_cases():
    # Gold locators are manually fixed, not generated by a retrieval strategy.
    return [
        Case("nearby_note", Sheet({(8, 3): "Feature", (8, 4): 5, (2, 4): "参数1"}, {(8, 4): "Daily attempts"}), (8, 3), {(8, 4, "comment"), (2, 4, "value")}),
        Case("distant_parallel_notes", Sheet({(20, 4): "Feature", (20, 5): 5, (7, 5): "参数1", (20, 20): "Feature", (7, 21): "参数1", (20, 21): "Daily attempts"}), (20, 4), {(7, 5, "value"), (20, 5, "value"), (20, 20, "value"), (7, 21, "value"), (20, 21, "value")}),
        Case("offset_header", Sheet({(35, 4): "Feature", (18, 5): "param1", (35, 5): 7}, {(35, 5): "Daily attempts"}), (35, 4), {(18, 5, "value"), (35, 5, "comment")}),
        Case("merged_header", Sheet({(8, 3): "Feature", (2, 4): "参数1", (8, 4): 5}, {(8, 4): "Daily attempts"}, [(2, 4, 2, 5)]), (8, 3), {(2, 4, "value"), (8, 4, "comment")}),
        Case("ambiguous_duplicate_fields", Sheet({(8, 3): "Feature", (2, 4): "参数1", (2, 5): "参数1", (8, 4): 5, (8, 5): 9}), (8, 3), {(2, 4, "value"), (2, 5, "value"), (8, 4, "value"), (8, 5, "value")}),
        # Deliberate unsupported case: evidence lives on another sheet.
        Case("separate_sheet_requires_followup", Sheet({(8, 3): "Feature", (2, 4): "参数1", (8, 4): 5}), (8, 3), {(2, 4, "value"), (-1, -1, "external_note")}),
        Case("field_left_of_key", Sheet({(8, 3): "Feature", (2, 2): "参数1", (8, 2): 5}, {(8, 2): "Daily attempts"}), (8, 3), {(2, 2, "value"), (8, 2, "comment")}),
        Case("unstructured_nearby_note", Sheet({(20, 4): "Feature", (20, 5): "备注", (20, 6): "Daily attempts"}), (20, 4), {(20, 5, "value"), (20, 6, "value")}),
    ]


def evaluate(cases):
    results = []
    for case in cases:
        for strategy in ("window", "row_headers", "structure", "adaptive"):
            metrics = select(case, strategy)
            start = time.perf_counter()
            for _ in range(30):
                select(case, strategy)
            metrics["selection_ms_mean"] = round((time.perf_counter() - start) * 1000 / 30, 3)
            results.append({"case": case.name, "cohort": case.cohort, "strategy": strategy, **metrics})
    return results


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    cases = synthetic_cases()
    if args.self_test:
        assert select(cases[1], "window")["complete"] is False
        assert select(cases[1], "structure")["complete"] is True
        assert select(cases[2], "row_headers")["complete"] is False
        assert select(cases[4], "structure")["covered"] == 4
        assert not select(cases[5], "structure")["complete"]
        assert select(cases[6], "structure")["complete"] is False
        assert select(cases[6], "adaptive")["complete"] is True
        assert select(cases[7], "adaptive")["selected_strategy"] == "row_headers"
    load_ms = None
    print(json.dumps({"workbook_load_ms": load_ms, "results": evaluate(cases)}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
